#!/usr/bin/env python3
"""Write data/media/nile/CREDITS.md from the manifest and the licence metadata.

    python3 -I tools/catalog/nile/write_credits.py

Lists every web-sourced image the Nile catalogue uses (title, author, licence, source URL), grouped
as: home-page photos, Wikimedia Commons product photos, DummyJSON product placeholders.
"""

from __future__ import annotations

import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
MEDIA = os.path.join(ROOT, "data", "media", "nile")
SRC = os.path.join(ROOT, "data", "media", "_src", "nile")


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def esc(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def main() -> int:
    with open(os.path.join(MEDIA, "manifest.json"), encoding="utf-8") as f:
        manifest = json.load(f)
    with open(os.path.join(ROOT, "data", "catalog", "nile.json"), encoding="utf-8") as f:
        catalog = json.load(f)
    with open(os.path.join(HERE, "hero_meta.json"), encoding="utf-8") as f:
        hero_meta = json.load(f)
    with open(os.path.join(SRC, "dummyjson-products.json"), encoding="utf-8") as f:
        dj = {p["id"]: p for p in json.load(f)["products"]}
    dj_by_url = {u: (pid, n) for pid, p in dj.items() for n, u in enumerate(p["images"], start=1)}
    credits = load(os.path.join(HERE, "commons_credits.py"), "cc")

    used = {}
    for p in catalog["products"]:
        for k in p["images"]:
            used[k] = p
    lines = [
        "# Nile media credits",
        "",
        "Every web-sourced image used by the Nile demo tenant. Files are generated by "
        "`tools/media/process.py` from the originals in `data/media/_src/nile/` (git-ignored); "
        "the per-key `source`, `license` and `credit` are also in `manifest.json`.",
        "",
        "## Home page photos (found via Openverse)",
        "",
        "| Keys | Title | Author | Provider | Licence | Source |",
        "|---|---|---|---|---|---|",
    ]
    for name, meta in hero_meta.items():
        keys = sorted(k for k, e in manifest.items() if e.get("source") == meta["url"])
        if not keys:
            continue
        lic = f"[CC0 {meta.get('license_version') or '1.0'}](https://creativecommons.org/publicdomain/zero/1.0/)"
        provider = meta.get("provider") or "WordPress Photo Directory"
        if provider == "wordpress":
            provider = "WordPress Photo Directory"
        lines.append(f"| {', '.join('`' + k + '`' for k in keys)} | {esc(meta['title'])} | {esc(meta['creator'])} | "
                     f"{esc(provider)} | {lic} | [photo page]({meta['foreign_landing_url']}) · [original]({meta['url']}) |")
    lines += [
        "",
        "## Product photos from Wikimedia Commons (via Openverse)",
        "",
        "| Keys | Product | Title | Author | Licence | Source | Changes |",
        "|---|---|---|---|---|---|---|",
    ]
    # key -> Commons stem, exactly as build_catalog.py assigns them
    import glob
    skel = dict(load(os.path.join(HERE, "skeleton.py"), "sk").PRODUCTS)
    for path in sorted(glob.glob(os.path.join(HERE, "parts", "*.py"))):
        skel.update(getattr(load(path, "p_" + os.path.basename(path)[:-3]), "SKELETON", {}))
    rows = {}
    for pid, (cat, img, *_rest) in sorted(skel.items()):
        if img[0] != "commons":
            continue
        for n, stem in enumerate(img[1:], start=1):
            key = f"nile/p{pid}-{n}"
            if key in used:
                rows.setdefault((stem, credits.FILES[stem]["title"]), []).append(key)
    for (stem, _), keys in sorted(rows.items(), key=lambda kv: kv[1][0]):
        meta = credits.FILES[stem]
        p = used[keys[0]]
        lic = f"[{credits.license_label(meta)}]({credits.license_url(meta)})"
        lines.append(f"| {', '.join('`' + k + '`' for k in keys)} | {esc(p['name']['en'])} | {esc(meta['title'])} | "
                     f"{esc(meta['creator'])} | {lic} | [file page]({meta['landing']}) | "
                     f"{esc(meta.get('changes', 'trimmed, scaled and re-encoded as WebP'))} |")
    lines += [
        "",
        "## Product placeholders from DummyJSON",
        "",
        "Licence for all rows: *DummyJSON demo asset — placeholder, replace with tenant photography* "
        "(credit: dummyjson.com). Each DummyJSON product's images are used in their API order.",
        "",
        "| Keys | Nile product | DummyJSON product | Source images |",
        "|---|---|---|---|",
    ]
    by_product = {}
    for k in sorted(used, key=lambda k: (used[k]["id"], int(k.rsplit("-", 1)[1]))):
        e = manifest.get(k, {})
        if e.get("credit") != "dummyjson.com":
            continue
        by_product.setdefault(used[k]["id"], []).append((k, e["source"]))
    for pid, items in by_product.items():
        p = used[items[0][0]]
        djids = []
        for _, url in items:
            d = dj_by_url.get(url, (None, None))[0]
            if d is not None and d not in djids:
                djids.append(d)
        titles = "; ".join(f"#{d} {esc(dj[d]['title'])}" for d in djids)
        links = " ".join(f"[{n}]({url})" for n, (_, url) in enumerate(items, start=1))
        keys = f"`{items[0][0]}`" + (f" … `{items[-1][0]}`" if len(items) > 1 else "")
        lines.append(f"| {keys} | {esc(p['name']['en'])} | {titles} | {links} |")
    lines.append("")
    out = os.path.join(MEDIA, "CREDITS.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.relpath(out, ROOT), len(rows), "commons rows,", len(by_product), "dummyjson products")
    return 0


if __name__ == "__main__":
    sys.exit(main())
