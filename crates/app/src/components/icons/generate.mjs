// Lucide (ISC) → one `d` string per icon, so every glyph is <svg><path d/></svg> and the islands
// router's lockstep DOM diff never meets two icons with different element trees.
import fs from "node:fs";
import vm from "node:vm";
const [dir, out, ...names] = process.argv.slice(2);
const pkg = JSON.parse(fs.readFileSync(`${dir}/../../../package.json`, "utf8"));
function load(name) {
  const src = fs.readFileSync(`${dir}/${name}.mjs`, "utf8");
  const re = src.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
  if (re) return load(re[1]);
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\nconst /);
  if (!m) throw new Error("no iconNode in " + name);
  return vm.runInNewContext(m[1]);
}
const n = (v) => {
  const s = (Math.round(Number(v) * 1000) / 1000).toString();
  return s.startsWith("0.") ? s.slice(1) : s.startsWith("-0.") ? "-" + s.slice(2) : s;
};
function absStart(d) {
  d = d.trim();
  if (d[0] === "M") return d;
  if (d[0] !== "m") throw new Error("path does not start with a moveto: " + d);
  const m = d.match(/^m([^a-zA-Z]*)/);
  const nums = m[1].match(/[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/g);
  const rest = d.slice(m[0].length);
  const head = `M${nums[0]} ${nums[1]}`;
  const tail = nums.length > 2 ? `l${nums.slice(2).join(" ")}` : "";
  return head + tail + rest;
}
function toPath([tag, a]) {
  switch (tag) {
    case "path":
      return absStart(a.d);
    case "circle": {
      const [cx, cy, r] = [+a.cx, +a.cy, +a.r];
      return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0z`;
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [+a.cx, +a.cy, +a.rx, +a.ry];
      return `M${n(cx - rx)} ${n(cy)}a${n(rx)} ${n(ry)} 0 1 0 ${n(2 * rx)} 0a${n(rx)} ${n(ry)} 0 1 0 ${n(-2 * rx)} 0z`;
    }
    case "rect": {
      const x = +(a.x ?? 0), y = +(a.y ?? 0), w = +a.width, h = +a.height;
      let rx = a.rx !== undefined ? +a.rx : a.ry !== undefined ? +a.ry : 0;
      let ry = a.ry !== undefined ? +a.ry : rx;
      rx = Math.min(rx, w / 2);
      ry = Math.min(ry, h / 2);
      if (!rx || !ry) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
      const arc = (dx, dy) => `a${n(rx)} ${n(ry)} 0 0 1 ${n(dx)} ${n(dy)}`;
      const hw = w - 2 * rx, hh = h - 2 * ry;
      return (
        `M${n(x + rx)} ${n(y)}` +
        (hw ? `h${n(hw)}` : "") + arc(rx, ry) +
        (hh ? `v${n(hh)}` : "") + arc(-rx, ry) +
        (hw ? `h${n(-hw)}` : "") + arc(-rx, -ry) +
        (hh ? `v${n(-hh)}` : "") + arc(rx, -ry) + "z"
      );
    }
    case "line":
      return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case "polyline":
    case "polygon": {
      const p = a.points.trim().split(/[\s,]+/).map(Number);
      let s = `M${n(p[0])} ${n(p[1])}`;
      for (let i = 2; i < p.length; i += 2) s += `L${n(p[i])} ${n(p[i + 1])}`;
      return tag === "polygon" ? s + "z" : s;
    }
    default:
      throw new Error("unknown element " + tag);
  }
}
const uniq = [...new Set(names)].sort();
let bytes = 0;
const arms = uniq.map((name) => {
  const d = load(name).map(toPath).join("");
  bytes += d.length;
  return `        "${name}" => "${d}",`;
});
const rs = `// @generated by the design-system agent from lucide-react ${pkg.version} (ISC licence,
// https://lucide.dev, © Lucide Contributors; a few glyphs derived from Feather, MIT © Cole Bemis).
// Each icon's elements (path, circle, rect, line, polyline) are rewritten as subpaths of ONE
// path, exactly: circles and rounded rects become arcs, lines and polylines become movetos and
// linetos. Drawn with stroke 2, round caps and joins, on the 24 grid, it renders the same as
// lucide's own markup. Do not edit by hand; regenerate with generate.mjs (see icons/mod.rs).

/// The single-path geometry of a lucide icon, or \`None\` for a name the kit doesn't ship.
pub fn path(name: &str) -> Option<&'static str> {
    Some(match name {
${arms.join("\n")}
        _ => return None,
    })
}

/// Every icon name the kit ships, sorted (the /ui page draws them all).
pub const NAMES: [&str; ${uniq.length}] = [
${uniq.map((u) => `    "${u}",`).join("\n")}
];
`;
fs.writeFileSync(out, rs);
console.log(`${uniq.length} icons, ${bytes} bytes of path data`);
