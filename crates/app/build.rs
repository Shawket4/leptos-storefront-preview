//! Builds the browser code: `client/` (TypeScript) is type-checked by `tsc` and bundled by esbuild
//! (`client/build.mjs`) into ES modules with code splitting — the entry, the features loaded on
//! demand and their shared chunks, every name a content hash. This writes `client_js.rs` into
//! OUT_DIR: a table of every file (name → bytes, embedded), the entry's path and the chunks the
//! entry imports statically (preloaded by the shell). `client_js` includes it; the server serves
//! `/js/{file}` from it, `immutable`.
//! Needs Node and `client/node_modules` (`npm ci --prefix client`).

use std::{env, fmt::Write as _, fs, path::PathBuf, process::Command};

fn main() {
    let client = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../client");
    for p in ["src", "build.mjs", "tsconfig.json", "package.json"] {
        println!("cargo:rerun-if-changed={}", client.join(p).display());
    }
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let js_dir = out_dir.join("js");
    let release = env::var("PROFILE").is_ok_and(|p| p == "release");

    let node = |args: &[&str]| {
        let status = Command::new("node").current_dir(&client).args(args).status();
        match status {
            Ok(s) if s.success() => {}
            Ok(_) => panic!("client build failed: node {}", args.join(" ")),
            Err(e) => panic!("client build needs Node.js on PATH ({e}); then `npm ci --prefix client`"),
        }
    };
    if !client.join("node_modules/esbuild").exists() {
        panic!("client/node_modules missing: run `npm ci --prefix client`");
    }
    node(&["node_modules/typescript/bin/tsc", "--noEmit", "-p", "."]);
    let js_dir_s = js_dir.to_string_lossy().into_owned();
    let mut args = vec!["build.mjs", "--outdir", js_dir_s.as_str()];
    if release {
        args.push("--release");
    }
    node(&args);

    // build.mjs's manifest: `entry <file>`, `preload <file>`, `file <file> <bytes>`, `import …`.
    let manifest = fs::read_to_string(js_dir.join("manifest.txt")).expect("client manifest written");
    let (mut entry, mut preload, mut files) = (String::new(), Vec::new(), Vec::new());
    for line in manifest.lines() {
        let mut parts = line.split(' ');
        match (parts.next(), parts.next()) {
            (Some("entry"), Some(f)) => entry = f.to_owned(),
            (Some("preload"), Some(f)) => preload.push(f.to_owned()),
            (Some("file"), Some(f)) => files.push(f.to_owned()),
            _ => {}
        }
    }
    assert!(!entry.is_empty(), "client manifest has no entry");

    let mut rs = String::from("// @generated by crates/app/build.rs from client/build.mjs's output.\n");
    writeln!(rs, "pub const APP_JS_PATH: &str = \"/js/{entry}\";").unwrap();
    writeln!(rs, "pub const APP_JS: &str = include_str!({:?});", js_dir.join(&entry).to_string_lossy()).unwrap();
    rs.push_str("/// Chunks the entry imports statically: fetched with it (`<link rel=modulepreload>`).\n");
    rs.push_str("pub const PRELOAD: &[&str] = &[");
    for f in &preload {
        write!(rs, "\"/js/{f}\", ").unwrap();
    }
    rs.push_str("];\n/// Every file of the bundle: (name, contents).\npub static FILES: &[(&str, &[u8])] = &[\n");
    for f in &files {
        writeln!(rs, "    ({f:?}, include_bytes!({:?})),", js_dir.join(f).to_string_lossy()).unwrap();
    }
    rs.push_str("];\n");
    fs::write(out_dir.join("client_js.rs"), rs).expect("client_js.rs written");
}
